"""
考点：位运算、分治
题目：Reverse Bits（颠倒二进制位）
思路：逐位反转，循环 32 次：result 左移一位，加上 n 的最低位，n 右移一位。
时间复杂度：O(1)
空间复杂度：O(1)
"""


def reverseBits(n: int) -> int:
    result = 0
    # 循环 32 次（32 位无符号整数）
    for _ in range(32):
        # result 左移 1 位，为新来的最低位腾出空间
        result = (result << 1) | (n & 1)
        # n 无符号右移 1 位（Python 中用 >> 即可，因为 n 作为非负整数处理）
        n >>= 1
    return result


if __name__ == "__main__":
    # n = 43261596 (二进制: 00000010100101000001111010011100)
    # 反转后 = 964176192 (二进制: 00111001011110000010100101000000)
    assert reverseBits(43261596) == 964176192
    # n = 4294967293 (二进制: 11111111111111111111111111111101)
    # 反转后 = 3221225471 (二进制: 10111111111111111111111111111111)
    assert reverseBits(4294967293) == 3221225471
    print("全部测试通过")
