"""
考点：位运算
题目：Number of 1 Bits（位1的个数）
题目描述：计算无符号整数的二进制表示中 1 的个数（汉明重量）。
  示例：n = 0b00000000000000000000000000001011 → 3
思路：方法一——循环检查每位，利用 n & 1 取最低位，然后 n >>= 1。
  方法二（更优）——Brian Kernighan 算法：n & (n-1) 会消掉最低位的 1。
  重复操作直至 n == 0，操作次数即 1 的个数。
时间复杂度：O(1)（32 位固定），或 O(k)（k 为 1 的个数）
空间复杂度：O(1)
"""


def hammingWeight(n: int) -> int:
    # Brian Kernighan 算法：
    # n & (n - 1) 会移除 n 的二进制表示中最右边的那个 1
    # 例如 n = 12 (1100), n-1 = 11 (1011), n & (n-1) = 1000（去掉了最低位的 1）
    count = 0
    while n != 0:
        n &= n - 1  # 每次去除一个最低位的 1
        count += 1
    return count


if __name__ == "__main__":
    assert hammingWeight(0b00000000000000000000000000001011) == 3
    assert hammingWeight(0b00000000000000000000000010000000) == 1
    assert hammingWeight(0b11111111111111111111111111111101) == 31
