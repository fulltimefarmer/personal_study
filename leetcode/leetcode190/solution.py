"""
考点：位运算、分治
题目：Reverse Bits（颠倒二进制位）
题目描述：颠倒给定的 32 位无符号整数的二进制位。
  示例：n = 0b00000010100101000001111010011100 → 0b00111001011110000010100101000000
思路：分治法。通过位移和掩码逐步交换相邻的位组（1位→2位→4位→8位→16位）。
  利用 Python 无符号右移的特性，使用掩码保证结果在 32 位范围内。
时间复杂度：O(1)
空间复杂度：O(1)
"""


def reverseBits(n: int) -> int:
    # Python 中整数是无限精度的，需要确保只在 32 位范围内操作
    # 分治法：逐步交换相邻位组，每次交换的组大小翻倍

    # 步骤1：交换奇数位和偶数位（每 1 位一组）
    # 0x55555555 = 0101_0101...（取奇数位），0xAAAAAAAA = 1010_1010...（取偶数位）
    n = ((n & 0x55555555) << 1) | ((n & 0xAAAAAAAA) >> 1)

    # 步骤2：每 2 位为一组，交换相邻组
    # 0x33333333 = 0011_0011...，0xCCCCCCCC = 1100_1100...
    n = ((n & 0x33333333) << 2) | ((n & 0xCCCCCCCC) >> 2)

    # 步骤3：每 4 位为一组，交换相邻组
    # 0x0F0F0F0F = 00001111...，0xF0F0F0F0 = 11110000...
    n = ((n & 0x0F0F0F0F) << 4) | ((n & 0xF0F0F0F0) >> 4)

    # 步骤4：每 8 位为一组，交换相邻组
    # 0x00FF00FF = 0000000011111111 0000000011111111
    # 0xFF00FF00 = 1111111100000000 1111111100000000
    n = ((n & 0x00FF00FF) << 8) | ((n & 0xFF00FF00) >> 8)

    # 步骤5：每 16 位为一组，交换相邻组（交换高 16 位和低 16 位）
    # Python 左移可能溢出 32 位，用 & 0xFFFFFFFF 截断
    n = ((n & 0x0000FFFF) << 16) | ((n & 0xFFFF0000) >> 16)

    # Python 返回时已在 32 位范围内，无需额外处理
    return n


if __name__ == "__main__":
    n1 = 0b00000010100101000001111010011100  # 43261596
    r1 = reverseBits(n1)
    assert r1 == 964176192  # 0b00111001011110000010100101000000

    n2 = 0b11111111111111111111111111111101  # 4294967293
    r2 = reverseBits(n2)
    assert r2 == 3221225471  # 0b10111111111111111111111111111111
