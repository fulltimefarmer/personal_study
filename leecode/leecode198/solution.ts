/**
 * 考点：Array, Dynamic Programming
 * 题目：House Robber
 * 题目描述：
 * 你是一个专业的小偷，计划偷窃沿街的房屋。每间房内都藏有一定的现金，影响你偷窃的唯一制约因素就是相邻的房屋装有相互连通的防盗系统，
 * 如果两间相邻的房屋在同一晚上被小偷闯入，系统会自动报警。
 * 给定一个代表每个房屋存放金额的非负整数数组，计算你今晚在不触动警报装置的情况下，能够偷窃到的最高金额。
 *
 * 示例 1：
 * 输入：[1,2,3,1]
 * 输出：4
 * 解释：偷窃 1 号房屋（金额 = 1），然后偷窃 3 号房屋（金额 = 3）。偷窃到的最高金额 = 1 + 3 = 4。
 *
 * 示例 2：
 * 输入：[2,7,9,3,1]
 * 输出：12
 * 解释：偷窃 1 号房屋（金额 = 2），偷窃 3 号房屋（金额 = 9），接着偷窃 5 号房屋（金额 = 1）。偷窃到的最高金额 = 2 + 9 + 1 = 12。
 *
 * 提示：
 * - 1 <= nums.length <= 100
 * - 0 <= nums[i] <= 400
 *
 * 思路：
 * 1. 定义 dp[i] 为偷窃前 i 间房屋（下标 0 到 i-1）能获得的最大金额。
 * 2. 对于第 i-1 间房屋，有两种选择：
 *    - 不偷该房屋，则金额为 dp[i-1]。
 *    - 偷该房屋，则不能偷第 i-2 间，金额为 dp[i-2] + nums[i-1]。
 * 3. 状态转移方程：dp[i] = max(dp[i-1], dp[i-2] + nums[i-1])。
 * 4. 使用滚动数组优化，只需保留代表 dp[i-1] 的 prev1 和代表 dp[i-2] 的 prev2。
 * 5. 遍历数组，计算 cur = max(prev1, prev2 + num)，然后更新 prev2 = prev1，prev1 = cur。
 * 6. 最终 prev1 即为能偷窃到的最高金额。
 * 数据结构/算法：动态规划；滚动数组。
 * 时间复杂度：O(n)
 * 空间复杂度：O(1)
 */
function rob(nums: number[]): number {
    let prev2 = 0;
    let prev1 = 0;
    for (const num of nums) {
        const cur = Math.max(prev1, prev2 + num);
        prev2 = prev1;
        prev1 = cur;
    }
    return prev1;
}
