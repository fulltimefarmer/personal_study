/**
 * 考点：String, Two Pointers
 * 题目：Reverse Words in a String
 * 题目描述：
 * 给你一个字符串 s，请你反转字符串中单词的顺序。
 *
 * 单词是由非空格字符组成的字符串。s 中使用至少一个空格将字符串中的单词分隔开。
 * 返回单词顺序颠倒且单词之间用单个空格连接的结果字符串。
 * 注意：输入字符串 s 中可能会存在前导空格、尾随空格或者单词间的多个空格。返回的结果字符串中，
 * 单词间应当仅用单个空格分隔，并确保结果字符串任何位置都不会出现前导空格和尾随空格。
 *
 * 示例 1：
 * 输入：s = "the sky is blue"
 * 输出："blue is sky the"
 *
 * 示例 2：
 * 输入：s = "  hello world  "
 * 输出："world hello"
 * 解释：反转后的字符串中不能存在前导空格和尾随空格。
 *
 * 示例 3：
 * 输入：s = "a good   example"
 * 输出："example good a"
 * 解释：如果两个单词间有多余空格，反转后的字符串需要将单词间的空格减少到仅有一个。
 *
 * 提示：
 * - 1 <= s.length <= 10^4
 * - s 包含英文大小写字母、数字和空格 ' '
 * - s 中至少存在一个单词
 *
 * 思路：
 * 1. 先对字符串 s 去除首尾空格，并按一个或多个空白字符将字符串分割成单词数组。
 * 2. 将单词数组进行反转，使原顺序变为倒序。
 * 3. 使用单个空格将反转后的单词拼接成一个新的字符串。
 * 4. 返回拼接后的结果，保证单词之间只有一个空格且无首尾空格。
 * 数据结构/算法：字符串分割与数组反转。
 * 时间复杂度：O(n)
 * 空间复杂度：O(n)
 */
function reverseWords(s: string): string {
    return s.trim().split(/\s+/).reverse().join(" ");
}
